import {createRequire} from 'node:module'
import assert from 'node:assert/strict'
const require=createRequire(import.meta.url)
const {chromium}=require(process.env.FACTORPOOL_PLAYWRIGHT_MODULE||'playwright')
const browser=await chromium.launch({headless:true})
const page=await browser.newPage({viewport:{width:1512,height:1050}})
const errors=[];page.on('pageerror',e=>errors.push(e.message))
await page.goto(process.env.FACTORPOOL_URL||'http://127.0.0.1:8088',{waitUntil:'networkidle'})
await page.getByRole('button',{name:'▶ 运行研究'}).click()
await page.locator('[data-testid=diagnostics]').waitFor({timeout:40000})
const report=page.locator('[data-testid=diagnostics]')
assert.equal(await report.locator('.ic-statistics tbody tr').count(),3)
await report.getByRole('button',{name:'5 期',exact:true}).click()
await report.getByLabel('诊断图表').selectOption('monthly')
await page.waitForTimeout(350)
await report.getByLabel('诊断图表').selectOption('decay')
await report.getByRole('button',{name:'多空与分组',exact:true}).click()
assert.ok(await report.locator('.portfolio-statistics tbody tr').count()>=8)
await report.getByLabel('研究组合').selectOption('short_G1')
await report.getByLabel('组合图表').selectOption('monthly')
await report.getByRole('button',{name:'BRAIN 风格',exact:true}).click()
assert.equal(await report.locator('.brain-metrics>div').count(),6)
assert.deepEqual(await report.locator('.brain-metrics span').allTextContents(),['Sharpe','Fitness','Returns','Turnover','Drawdown','Margin'])
assert.equal(await report.locator('.brain-missing b').allTextContents().then(x=>x.every(v=>v==='--')),true)
await page.waitForTimeout(500)
const output=process.env.FACTORPOOL_BROWSER_OUTPUT||'/tmp'
await page.screenshot({path:`${output}/brain-diagnostics-desktop.png`,fullPage:true})
await page.setViewportSize({width:390,height:844})
await page.waitForTimeout(500)
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=392))
await page.screenshot({path:`${output}/brain-diagnostics-mobile.png`,fullPage:true})
assert.deepEqual(errors,[])
console.log(JSON.stringify({periods:'1/5/20',ic:'passed',portfolios:'passed',brain_cards:6,mobile:'passed',browser_errors:errors}))
await browser.close()
