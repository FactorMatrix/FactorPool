import {fixtureScript, runResearch, setSource} from './browser-script-utils.mjs'
import {createRequire} from 'node:module'
import assert from 'node:assert/strict'
const base=process.env.FACTORPOOL_URL
if (!base?.trim()) throw new Error('FACTORPOOL_URL must name an isolated browser test stack; no default target is allowed')
const require=createRequire(import.meta.url)
const {chromium}=require(process.env.FACTORPOOL_PLAYWRIGHT_MODULE||'playwright')
const browser=await chromium.launch({headless:true})
const page=await browser.newPage({viewport:{width:1512,height:1050}})
const errors=[];page.on('pageerror',e=>errors.push(e.message))
await page.goto(base,{waitUntil:'networkidle'})
await setSource(page, fixtureScript({horizons:[1,5,20]}))
const taskId=await runResearch(page)
await page.getByRole('button',{name:'IC Analysis',exact:true}).click()
await page.locator('[data-testid=diagnostics]').waitFor()
const report=page.locator('[data-testid=diagnostics]')
assert.equal(await report.locator('.ic-statistics tbody tr').count(),1)
assert.equal(await report.getByRole('button',{name:'5 期',exact:true}).count(),0)
await report.getByLabel('诊断图表').selectOption('monthly')
await page.waitForTimeout(350)
await report.getByLabel('诊断图表').selectOption('decay')
await report.getByRole('button',{name:'多空与分组',exact:true}).click()
assert.ok(await report.locator('.portfolio-statistics tbody tr').count()>=8)
await report.getByLabel('研究组合').selectOption('short_G1')
await report.getByLabel('组合图表').selectOption('monthly')
assert.equal(await report.getByRole('button',{name:'BRAIN 风格',exact:true}).count(),0,'The obsolete duplicate BRAIN view must be removed')
assert.equal(await report.locator('.brain-metrics').count(),0)
await page.getByRole('button',{name:'Summary',exact:true}).click()
const actual=await(await page.request.get(`${base}/api/tasks/${taskId}/result`)).json()
const stats=actual.diagnostics.horizons['1'].portfolios.alpha.brain_style
const number=value=>value==null?'—':Number(value).toFixed(2)
const percent=value=>value==null?'—':`${(Number(value)*100).toFixed(2)}%`
assert.deepEqual(await page.locator('.summary-measure strong').allTextContents(),[
 number(stats.sharpe),percent(stats.turnover),number(stats.fitness),percent(stats.returns),percent(stats.drawdown),stats.margin==null?'—':`${(stats.margin*10000).toFixed(2)} bps`])
await page.getByRole('button',{name:'Correlation',exact:true}).click()
assert.deepEqual(await page.locator('.correlation-values strong').allTextContents(),['—','—','—'])
await page.waitForTimeout(500)
const output=process.env.FACTORPOOL_BROWSER_OUTPUT||'/tmp'
await page.screenshot({path:`${output}/brain-diagnostics-desktop.png`,fullPage:true})
await page.setViewportSize({width:390,height:844})
await page.waitForTimeout(500)
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=392))
await page.screenshot({path:`${output}/brain-diagnostics-mobile.png`,fullPage:true})
assert.deepEqual(errors,[])
console.log(JSON.stringify({periods:'1D UI; explicit 1/5/20 API retained',ic:'passed',portfolios:'passed',core_summary_cards:6,duplicate_brain_view:'removed',mobile:'passed',browser_errors:errors}))
await browser.close()
