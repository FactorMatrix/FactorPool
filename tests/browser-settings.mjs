// Run on an explicit isolated stack: these checks create synthetic research tasks.
import {createRequire} from 'node:module'
import assert from 'node:assert/strict'
import {fixtureConfig, fixtureScript, pythonLiteral, readSource, runResearch, setSource} from './browser-script-utils.mjs'
const base = process.env.FACTORPOOL_URL
if (!base?.trim()) throw new Error('FACTORPOOL_URL must name an isolated browser test stack; no default target is allowed')
const require = createRequire(import.meta.url)
const {chromium} = require(process.env.FACTORPOOL_PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({headless:true})
const page = await browser.newPage({viewport:{width:1512,height:1050}})
const output = process.env.FACTORPOOL_BROWSER_OUTPUT || '/tmp'
const errors = [], submissions = []
const fixtureName = `浏览器验收 · 设置默认与config覆盖 · ${Date.now()}`
page.on('pageerror', error => errors.push(error.message))
page.on('request', request => {
  if (request.method() === 'POST' && request.url().endsWith('/api/tasks')) submissions.push(request.postDataJSON())
})
const settings = page.getByRole('region', {name:'模拟设置',exact:true})
const settingButton = page.getByRole('button', {name:'设置',exact:true})
async function preview() {
  const response = page.waitForResponse(value => value.request().method() === 'POST' && value.url().endsWith('/api/script/resolve'))
  await settings.getByRole('button', {name:'校验源码配置',exact:true}).click()
  const result = await response
  assert.equal(result.status(),200,await result.text())
  await settings.getByLabel('有效配置',{exact:true}).waitFor()
  return result.json()
}
async function run() {
  const id = await runResearch(page)
  assert.ok(id)
  return {id, task:await (await page.request.get(`${base}/api/tasks/${id}`)).json(),
    values:await (await page.request.get(`${base}/api/tasks/${id}/values`)).json(),
    result:await (await page.request.get(`${base}/api/tasks/${id}/result`)).json()}
}
try {
  await page.goto(base,{waitUntil:'networkidle'})
  const factorNav = page.getByRole('button',{name:'因子库',exact:true})
  assert.match(await factorNav.innerText(),/Factors/)
  assert.equal(await factorNav.locator('svg path').getAttribute('d'),'M7 21V3h12 M7 11h10')
  assert.equal(await page.locator('.factor-name select').count(),0)
  assert.equal(await page.getByText('config 脚本',{exact:true}).count(),0)
  assert.equal(await page.getByText('历史类入口',{exact:true}).count(),0)
  assert.equal(await settingButton.count(),1)
  const options = {period:3,start:'2024-01-04',end:'2024-01-08',horizons:[1,5],meanClose:true}
  const template = fixtureScript(options), literal = pythonLiteral(fixtureConfig(options))
  const emptySource = template.replace(`config = ${literal}`,'config = {}')
  await setSource(page,emptySource)
  await page.getByLabel('因子名称',{exact:true}).fill(fixtureName)
  await settingButton.click()
  assert.equal(await settingButton.getAttribute('aria-expanded'),'true')
  assert.equal(await settings.getByLabel('因子类',{exact:true}).count(),0)
  await settings.getByLabel('数据源',{exact:true}).selectOption('fixture')
  await settings.getByLabel('开始日期',{exact:true}).fill('2024-01-04')
  await settings.getByLabel('结束日期',{exact:true}).fill('2024-01-08')
  await settings.getByLabel('构造参数 JSON',{exact:true}).fill('{"period":3}')
  await settings.getByLabel('分析周期',{exact:true}).fill('1,5')
  await settings.getByLabel('分组数',{exact:true}).fill('3')
  await settings.getByLabel('衰减阶数',{exact:true}).fill('2')
  await settings.getByLabel('权重衰减',{exact:true}).fill('5')
  await settings.getByLabel('中性化',{exact:true}).selectOption('NONE')
  await settings.getByLabel('单股权重上限',{exact:true}).fill('0.2')
  await settings.getByLabel('测试期',{exact:true}).fill('P0Y0M')
  await settings.getByLabel('图表',{exact:true}).selectOption('true')
  await settings.locator('.advanced-settings summary').click()
  await settings.getByLabel('追踪日期',{exact:true}).fill('2024-01-04')
  const empty = await preview()
  assert.deepEqual(empty.source_config,{})
  assert.equal(empty.data.provider,'fixture')
  assert.equal(empty.factor_params.period,3)
  assert.equal(empty.brain_settings.decay,5)
  assert.equal(empty.brain_settings.visualization,true)
  assert.deepEqual(empty.analysis.trace_dates,['2024-01-04'])
  await page.screenshot({path:`${output}/settings-desktop.png`,fullPage:true})
  await settings.getByRole('button',{name:'应用设置',exact:true}).click()
  assert.equal(await settings.count(),0)
  const first = await run()
  assert.deepEqual(Object.keys(submissions[0]).sort(),['name','source_code','workspace_config'])
  assert.equal(submissions[0].workspace_config.factor.period,3)
  assert.equal(first.task.snapshot.factor_params.period,3)
  assert.deepEqual(first.task.snapshot.source_config,{})
  assert.ok(Math.abs(first.values[0].value-(10+11+12.1)/3)<1e-12)

  const partialConfig = {base:{start_date:'2024-01-05'},factor:{period:1},
    analysis:{trace_dates:[]},settings:{decay:0,truncation:0,visualization:false}}
  const partialSource = template.replace(`config = ${literal}`,`config = ${pythonLiteral(partialConfig)}`)
  await setSource(page,partialSource)
  await settingButton.click()
  const partial = await preview()
  assert.deepEqual(partial.source_config,partialConfig)
  assert.equal(partial.data.factor_start,'2024-01-05')
  assert.equal(partial.data.factor_end,'2024-01-08')
  assert.equal(partial.data.provider,'fixture')
  assert.equal(partial.factor_params.period,1)
  assert.equal(partial.brain_settings.decay,0)
  assert.equal(partial.brain_settings.truncation,0)
  assert.equal(partial.brain_settings.visualization,false)
  assert.equal(partial.brain_settings.neutralization,'NONE')
  assert.deepEqual(partial.analysis.trace_dates,[])
  assert.deepEqual(partial.analysis.horizons,[1,5])
  await settings.getByRole('button',{name:'关闭设置',exact:true}).click()
  const second = await run()
  assert.equal(second.task.snapshot.workspace_config.factor.period,3)
  assert.equal(second.task.snapshot.factor_params.period,1)
  assert.deepEqual(second.task.snapshot.source_config,partialConfig)
  assert.equal(second.result.metadata.effective_config.settings.visualization,false)
  assert.equal(second.result.metadata.effective_config.settings.truncation,0)
  assert.ok(Math.abs(second.values[0].value-13.31)<1e-12)
  assert.equal(await page.locator('.simulation-chart-panel .report-chart').count(),0)
  assert.deepEqual((await (await page.request.get(`${base}/api/tasks/${first.id}`)).json()).snapshot,first.task.snapshot)

  const noConfig = template.replace(`config = ${literal}\n`,'').replace('MatrixFactor.run(config)','MatrixFactor.run()')
  await setSource(page,noConfig)
  assert.equal(await readSource(page),noConfig)
  const third = await run()
  assert.deepEqual(third.task.snapshot.source_config,{})
  assert.equal(third.task.snapshot.factor_params.period,3)
  assert.equal(third.result.metadata.effective_config.settings.visualization,true)
  assert.ok(Math.abs(third.values[0].value-first.values[0].value)<1e-12)
  const classOnly = template.split('if __name__')[0].replace(`config = ${literal}\n`,'')
  const rejected = await page.request.post(`${base}/api/tasks`,{data:{name:'浏览器验收 · 删除旧入口',source_code:classOnly,
    factor_class:'MatrixFactor',factor_params:{period:3},data:{provider:'fixture',universe:'fixture'}}})
  assert.equal(rejected.status(),400)

  await page.getByRole('button',{name:'保存版本',exact:true}).click()
  await page.locator('.notice').filter({hasText:'已保存版本'}).waitFor()
  await factorNav.click()
  const savedRow = page.locator('.page tbody tr').filter({hasText:fixtureName})
  assert.equal(await savedRow.count(),1)
  await savedRow.getByRole('button',{name:'打开',exact:true}).click()
  assert.equal(await readSource(page),noConfig)
  await settingButton.click()
  assert.equal(await settings.getByLabel('数据源',{exact:true}).inputValue(),'fixture')
  assert.equal(await settings.getByLabel('构造参数 JSON',{exact:true}).inputValue(),'{\n  "period": 3\n}')
  assert.equal(await settings.getByLabel('权重衰减',{exact:true}).inputValue(),'5')
  await page.setViewportSize({width:390,height:844})
  await page.waitForTimeout(350)
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth<=392),'Settings caused mobile body overflow')
  await page.screenshot({path:`${output}/settings-mobile.png`,fullPage:true})
  await settings.getByRole('button',{name:'关闭设置',exact:true}).click()
  assert.equal(submissions.length,3)
  assert.deepEqual(errors,[])
  console.log(JSON.stringify({tasks:[first.id,second.id,third.id],icon:'Factor F, no alpha path',entry:'one settings button, no mode or class selector',
    config:'empty / partial / absent, nested precedence and explicit 0 False []',state:'saved settings restored, original snapshot unchanged',mobile:'passed',browser_errors:errors}))
} finally { await browser.close() }
