import { createRequire } from 'node:module'
import assert from 'node:assert/strict'
import { readSource, setSource } from './browser-script-utils.mjs'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.FACTORPOOL_PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.FACTORPOOL_URL || 'http://127.0.0.1:8088'
const output = process.env.FACTORPOOL_BROWSER_OUTPUT || '/tmp'
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1512, height: 1050 } })
const errors = [], submissions = []
page.on('pageerror', error => errors.push(error.message))
page.on('request', request => {
  if (request.method() === 'POST' && request.url().endsWith('/api/tasks')) submissions.push(request.postDataJSON())
})
try {
  await page.goto(base, { waitUntil: 'networkidle' })
  const original = await readSource(page)
  await page.getByRole('button', { name: '使用说明', exact: true }).click()
  const docs = page.getByRole('region', { name: '使用教程', exact: true })
  await docs.locator('[data-page="welcome"]').waitFor()
  assert.ok(await docs.locator('[data-doc-page]').count() >= 12)
  assert.equal(await docs.locator('.doc-code').count(), 0, 'Landing page should introduce the docs before showing a full script')
  assert.ok(await docs.getByRole('complementary', { name: '页内目录', exact: true }).isVisible())
  await page.screenshot({ path: `${output}/learn-documentation-desktop.png`, fullPage: true })
  await docs.locator('[data-doc-page="quick-start"]').click()
  const sample = await docs.getByLabel('入门完整脚本', { exact: true }).innerText()
  const preview = await page.request.post(`${base}/api/script/resolve`, { data: { source_code: sample } })
  assert.equal(preview.status(), 200, await preview.text())
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  await docs.getByRole('button', { name: '复制完整示例', exact: true }).click()
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), sample)
  // IP addresses commonly use HTTP: exercise the user-initiated copy fallback.
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { value: undefined, configurable: true }))
  await docs.getByRole('button', { name: '复制完整示例', exact: true }).click()
  await page.evaluate(() => { delete navigator.clipboard })
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), sample)

  await docs.getByLabel('搜索文档', { exact: true }).fill('ts_mean')
  await docs.locator('.docs-search-results button').filter({ hasText: /^ts_mean/ }).click()
  await docs.getByRole('heading', { name: 'ts_mean', exact: true }).waitFor()
  assert.ok(page.url().endsWith('#learn/operators/ts_mean'))
  assert.match(await docs.locator('[data-section="example"]').innerText(), /当前输出 2/)
  await docs.getByRole('complementary', { name: '页内目录', exact: true }).getByRole('button', { name: '参数', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.docs-viewport').scrollTop > 40)
  await page.reload({ waitUntil: 'networkidle' })
  await docs.getByRole('heading', { name: 'ts_mean', exact: true }).waitFor()
  await page.screenshot({ path: `${output}/learn-operator-detail.png`, fullPage: true })
  await docs.locator('[data-doc-page="operators"]').click()
  await docs.getByLabel('算子搜索', { exact: true }).waitFor()
  const operators = await (await page.request.get(`${base}/api/operators`)).json()
  assert.equal(operators.length, 66)
  assert.equal(await docs.locator('[data-operator]').count(), 66)
  assert.equal(await docs.locator('[data-operator] .doc-status.available').count(), 40)
  assert.equal(await docs.getByLabel('算子状态', { exact: true }).count(), 0)
  assert.deepEqual(await docs.locator('[data-operator-group]').evaluateAll(items => items.map(item => item.dataset.operatorGroup)), ['arithmetic', 'logical', 'ts', 'cs', 'vector', 'transform', 'group'])
  for (const [name, group] of [['add', 'arithmetic'], ['and', 'logical'], ['ts_mean', 'ts'], ['rank', 'cs'], ['group_rank', 'group']]) {
    assert.equal(await docs.locator(`[data-operator="${name}"]`).evaluate(el => el.closest('[data-operator-group]').dataset.operatorGroup), group)
  }
  const fontSizes = await docs.locator('[data-operator="add"]').evaluate(el => ({ name: parseFloat(getComputedStyle(el.querySelector('strong')).fontSize), usage: parseFloat(getComputedStyle(el.querySelector('code')).fontSize), description: parseFloat(getComputedStyle(el.querySelector('p')).fontSize) }))
  assert.ok(fontSizes.name >= 18 && fontSizes.usage >= 14 && fontSizes.description >= 16, JSON.stringify(fontSizes))
  await page.screenshot({ path: `${output}/learn-operator-groups.png`, fullPage: true })
  const visibleBeforeJump = await docs.locator('[data-operator]').count()
  await docs.locator('[data-operator-category="ts"]').click()
  await page.waitForFunction(() => document.querySelector('.docs-viewport').scrollTop > 100)
  assert.equal(await docs.locator('[data-operator]').count(), visibleBeforeJump, 'Chapter links scroll without filtering other sections')
  assert.equal(await docs.locator('[data-operator-group]').count(), 7)
  await page.screenshot({ path: `${output}/learn-time-series-heading.png`, fullPage: true })
  await docs.getByLabel('算子搜索', { exact: true }).fill('trade_when')
  const pending = docs.locator('[data-operator="trade_when"]')
  await pending.waitFor()
  assert.equal(await pending.locator('.doc-status').innerText(), '待接通')
  await pending.click()
  await docs.getByRole('heading', { name: 'trade_when', exact: true }).waitFor()
  assert.match(await docs.locator('[data-section="example"]').innerText(), /尚未接通/)
  await page.goBack()
  await pending.waitFor()

  await docs.locator('[data-doc-page="settings"]').click()
  await docs.getByLabel('设置搜索', { exact: true }).fill('neutralization')
  await docs.locator('[data-setting="neutralization"]').click()
  await docs.getByRole('heading', { name: 'neutralization', exact: true }).waitFor()
  const options = await docs.locator('[data-section="setting-options"]').innerText()
  assert.match(options, /NONE/); assert.match(options, /MARKET/); assert.match(options, /INDUSTRY/); assert.match(options, /缺.*数据/)
  await page.screenshot({ path: `${output}/learn-settings-detail.png`, fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await docs.getByRole('button', { name: '打开文档目录', exact: true }).click()
  await docs.locator('[data-doc-page="quick-start"]').click()
  await docs.getByLabel('入门完整脚本', { exact: true }).waitFor()
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= 392), 'Documentation must fit a phone viewport')
  assert.ok(await docs.evaluate(el => el.scrollWidth <= el.clientWidth + 1), 'Code and tables must scroll inside their own containers')
  assert.equal(await docs.getByRole('complementary', { name: '文档目录', exact: true }).isVisible(), false)
  await page.screenshot({ path: `${output}/learn-documentation-mobile.png`, fullPage: true })
  await docs.getByRole('button', { name: '打开文档目录', exact: true }).click()
  await docs.locator('[data-doc-page="operators"]').click()
  await docs.getByLabel('算子搜索', { exact: true }).waitFor()
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= 392), 'Grouped operator headings and larger text must fit on phones')
  assert.equal(await docs.locator('[data-operator-group]').count(), 7)
  await page.screenshot({ path: `${output}/learn-operator-groups-mobile.png`, fullPage: true })
  await page.setViewportSize({ width: 1512, height: 1050 })
  await docs.locator('[data-doc-page="quick-start"]').click()
  await docs.getByRole('heading', { name: '创建第一个因子', exact: true }).click()
  await page.keyboard.press('/')
  assert.equal(await docs.getByLabel('搜索文档', { exact: true }).evaluate(el => document.activeElement === el), true)
  await page.keyboard.press('Escape')
  assert.equal(submissions.length, 0)
  await page.getByRole('button', { name: '研究', exact: true }).click()
  assert.equal(await readSource(page), original)

  await setSource(page, sample)
  await page.getByRole('button', { name: '运行研究', exact: true }).click()
  await page.locator('.badge.SUCCEEDED').waitFor({ timeout: 40000 })
  await page.getByRole('button', { name: 'Factor Values', exact: true }).click()
  const task = await page.evaluate(() => sessionStorage.getItem('factorpool.task'))
  const report = await (await page.request.get(`${base}/api/tasks/${task}/result`)).json()
  assert.equal(report.metadata.synthetic, true); assert.ok(report.metadata.value_count > 0)
  const values = await page.locator('.factor-values').innerText()
  await page.getByRole('button', { name: '使用说明', exact: true }).click()
  await docs.locator('[data-page="welcome"]').waitFor()
  await page.getByRole('button', { name: '研究', exact: true }).click()
  await page.getByRole('button', { name: 'Factor Values', exact: true }).click()
  assert.equal(await page.locator('.factor-values').innerText(), values)
  assert.equal(await readSource(page), sample)
  assert.equal(submissions.length, 1)

  const outage = await browser.newPage()
  outage.on('pageerror', error => errors.push(error.message))
  await outage.route('**/api/simulation-settings', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: '设置说明暂时不可用' }) }))
  await outage.goto(`${base}/#learn/settings`, { waitUntil: 'networkidle' })
  await outage.getByRole('button', { name: '重试', exact: true }).waitFor()
  await outage.unroute('**/api/simulation-settings')
  await outage.getByRole('button', { name: '重试', exact: true }).click()
  await outage.getByLabel('设置搜索', { exact: true }).waitFor()
  await outage.close()
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ documentation: 'chapter navigation, operator/setting detail, search, TOC, history and deep links passed', sample: 'AST validated and fixture research succeeded', copy: 'clipboard API and HTTP fallback passed', state: 'draft and task results preserved', retry: 'isolated catalog outage recovered', desktop: 'passed', mobile: 'passed', browser_errors: errors }))
} finally { await browser.close() }
