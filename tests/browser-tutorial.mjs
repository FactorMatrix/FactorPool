  await mean.locator('.operator-details').waitFor()
  assert.ok(page.url().endsWith('#learn/operators'), 'Search opens an index disclosure rather than a detail route')
  assert.match(await mean.locator('[data-detail-section="example"]').innerText(), /当前输出 2/)
