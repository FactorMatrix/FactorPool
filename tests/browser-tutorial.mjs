import { createRequire } from 'node:module'
import assert from 'node:assert/strict'
import { readSource, setSource } from './browser-script-utils.mjs'

const require = createRequire(import.meta.url)
const { chromium } = require(process.env.FACTORPOOL_PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.FACTORPOOL_URL || 'http://127.0.0.1:8088'
const output = process.env.FACTORPOOL_BROWSER_OUTPUT || '/tmp'
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1512, height: 1050 } })
const errors = [], submissions = []
page.on('pageerror', e => errors.push(e.message))
page.on('request', request => {
  if (request.method() === 'POST' && request.url().endsWith('/api/tasks')) submissions.push(request.postDataJSON())
})
try {
  await page.goto(base, { waitUntil: 'networkidle' })
  const original = await readSource(page)
  await page.getByRole('button', { name: '使用说明', exact: true }).click()
  const tutorial = page.getByRole('region', { name: '使用教程', exact: true })
  await tutorial.waitFor()
  const sample = await tutorial.getByLabel('入门完整脚本', { exact: true }).innerText()
  assert.match(sample, /from factorpool import PythonIndicator/)
  assert.match(sample, /\.run\(config\)/)
  const preview = await page.request.post(`${base}/api/script/resolve`, { data: { source_code: sample } })
  assert.equal(preview.status(), 200, await preview.text())
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  await tutorial.getByRole('button', { name: '复制完整示例', exact: true }).click()
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), sample)
  assert.equal(submissions.length, 0, 'Reading or validating help must not start a task')
  await page.screenshot({ path: `${output}/tutorial-desktop.png`, fullPage: true })

  await tutorial.getByRole('button', { name: '算子', exact: true }).click()
  const search = tutorial.getByLabel('算子搜索', { exact: true })
  const operators = await (await page.request.get(`${base}/api/operators`)).json()
  await tutorial.getByLabel('算子状态', { exact: true }).selectOption('connected')
  assert.equal(await tutorial.locator('[data-operator]').count(), operators.filter(x => x.native && x.pool_wiring === 'connected').length)
  await search.fill('ts_mean')
  await tutorial.locator('[data-operator="ts_mean"]').waitFor()
  assert.match(await tutorial.locator('[data-operator="ts_mean"]').innerText(), /self\.ts\.mean/)
  await tutorial.getByLabel('算子状态', { exact: true }).selectOption('all')
  await search.fill('trade_when')
  const pending = tutorial.locator('[data-operator="trade_when"]')
  await pending.waitFor()
  assert.equal(await pending.locator('.tutorial-tag').innerText(), '待接通')

  await tutorial.getByRole('button', { name: '设置', exact: true }).click()
  await tutorial.getByLabel('设置搜索', { exact: true }).fill('neutralization')
  const setting = tutorial.locator('[data-setting="neutralization"]')
  await setting.waitFor()
  await setting.locator('summary').first().click()
  const settingText = await setting.innerText()
  assert.match(settingText, /MARKET/)
  assert.match(settingText, /NONE/)
  assert.match(settingText, /INDUSTRY/)
  assert.match(settingText, /缺.*数据/)

  await page.setViewportSize({ width: 390, height: 844 })
  await tutorial.scrollIntoViewIfNeeded()
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= 392), 'Tutorial must fit a phone viewport')
  assert.ok(await tutorial.evaluate(el => el.scrollWidth <= el.clientWidth + 1), 'Tutorial cards must not overflow the result pane')
  await page.screenshot({ path: `${output}/tutorial-mobile.png`, fullPage: true })
  await page.setViewportSize({ width: 1512, height: 1050 })
  await page.getByRole('button', { name: '研究', exact: true }).click()
  assert.equal(await readSource(page), original, 'Reading Learn must preserve the draft')

  const source = sample
  await setSource(page, source)
  await page.getByRole('button', { name: '运行研究', exact: true }).click()
  await page.locator('.badge.SUCCEEDED').waitFor({ timeout: 40000 })
  await page.getByRole('button', { name: 'Factor Values', exact: true }).click()
  const task = await page.evaluate(() => sessionStorage.getItem('factorpool.task'))
  const report = await (await page.request.get(`${base}/api/tasks/${task}/result`)).json()
  assert.equal(report.metadata.synthetic, true)
  assert.ok(report.metadata.value_count > 0)
  const values = await page.locator('.factor-values').innerText()
  await page.getByRole('button', { name: '使用说明', exact: true }).click()
  await tutorial.waitFor()
  await page.getByRole('button', { name: '研究', exact: true }).click()
  await page.getByRole('button', { name: 'Factor Values', exact: true }).click()
  assert.equal(await page.locator('.factor-values').innerText(), values)
  assert.equal(await page.evaluate(() => sessionStorage.getItem('factorpool.task')), task)
  assert.equal(await readSource(page), source)
  assert.equal(submissions.length, 1)

  // A catalog outage belongs to help and must not prevent editing or research.
  await page.route('**/api/simulation-settings', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: '教程配置暂时不可用' }) }))
  await page.getByRole('button', { name: '使用说明', exact: true }).click()
  await tutorial.getByRole('button', { name: '设置', exact: true }).click()
  await tutorial.getByRole('button', { name: '重试', exact: true }).waitFor()
  assert.match(await tutorial.innerText(), /教程配置暂时不可用/)
  await page.unroute('**/api/simulation-settings')
  await tutorial.getByRole('button', { name: '重试', exact: true }).click()
  await tutorial.getByLabel('设置搜索', { exact: true }).waitFor()
  await page.getByRole('button', { name: '研究', exact: true }).click()
  await page.getByRole('button', { name: 'Factor Values', exact: true }).click()
  assert.equal(await page.locator('.factor-values').innerText(), values)
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ tutorial: 'quick start, live operators and settings passed', sample: 'server AST validated', state: 'draft and selected result preserved', errors: 'catalog retry isolated from research', desktop: 'passed', mobile: 'passed', browser_errors: errors }))
} finally {
  await browser.close()
}
