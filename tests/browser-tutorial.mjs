  assert.equal(page.url(), urlBeforeToggle)
  assert.deepEqual(await add.locator('.operator-details > [data-detail-section]').evaluateAll(items => items.map(item => item.dataset.detailSection)), ['purpose','signature','parameters','example','boundaries','advanced'])
  assert.doesNotMatch(await add.locator('.operator-details').innerText(), /时序示例/)
  const advancedAdd = add.locator('[data-detail-section="advanced"]')
  assert.equal(await advancedAdd.getAttribute('open'), null)
