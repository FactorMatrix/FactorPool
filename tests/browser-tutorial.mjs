  await docs.getByLabel('算子搜索', {exact:true}).fill('gp.zscore')
  assert.equal(await docs.locator('[data-operator]').count(), 1)
  const groupZscore = docs.locator('[data-operator="group_zscore"]')
  await groupZscore.locator(':scope > .reference-toggle').click()
  assert.match(await groupZscore.locator('[data-detail-section="signature"]').innerText(), /self\.gp\.zscore/)
  assert.match(await groupZscore.locator('[data-detail-section="example"]').innerText(), /g.*0.*0.*0.*1/)
  await docs.getByLabel('算子搜索', {exact:true}).fill('group_mean')
