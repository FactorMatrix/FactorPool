  await groupMean.locator(':scope > .reference-toggle').click()
  assert.match(await groupMean.locator('[data-detail-section="signature"]').innerText(), /self\.gp\.mean\(x, g, weight=1\)/)
  await groupMean.locator('[data-detail-section="advanced"] summary').click()
  assert.match(await groupMean.locator('[data-detail-section="advanced"]').innerText(), /关键字/)
  await docs.getByLabel('算子搜索', {exact:true}).fill('')
  await page.screenshot({ path: `${output}/learn-operator-inline.png`, fullPage: true })
  const visibleBeforeJump = await docs.locator('[data-operator]').count()
