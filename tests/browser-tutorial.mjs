  assert.equal(await docs.locator('[data-operator-group]').count(), 7)
  await page.screenshot({ path: `${output}/learn-time-series-heading.png`, fullPage: true })

  // Existing bookmarks still open the corresponding item inside the full index.
  const linked = await browser.newPage({ viewport: { width: 1512, height: 1050 } })
  linked.on('pageerror', error => errors.push(error.message))
  await linked.goto(`${base}/#learn/operators/ts_mean`, { waitUntil: 'networkidle' })
  await linked.locator('[data-operator="ts_mean"] .operator-details').waitFor()
  assert.equal(await linked.locator('[data-operator]').count(), operators.length)
